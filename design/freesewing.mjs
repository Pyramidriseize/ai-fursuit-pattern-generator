// Generates real made-to-measure patterns with FreeSewing (MIT, see CREDITS.md) for the blueprint sheets.
// Writes printable SVGs at true size plus a data file the sheet pages load.
// Usage: node freesewing.mjs <print-dir> <data-file>
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { Hi } from '@freesewing/hi';
import { Titan } from '@freesewing/titan';
import { Brian } from '@freesewing/brian';
import { pluginTheme } from '@freesewing/plugin-theme';

// One adult wearer in millimetres. The head matches the 58 cm used on the head base sheet.
const BODY = {
  ankle: 240, biceps: 335, chest: 1000, crossSeam: 760, crossSeamFront: 370, head: 580, heel: 330, hips: 960, hpsToBust: 280,
  hpsToWaistBack: 450, hpsToWaistFront: 440, inseam: 790, knee: 400, neck: 400, seat: 1000, seatBack: 510, shoulderSlope: 13,
  shoulderToElbow: 360, shoulderToShoulder: 450, shoulderToWrist: 640, upperLeg: 590, waist: 860, waistBack: 430, waistToArmpit: 230,
  waistToFloor: 1060, waistToHips: 120, waistToKnee: 610, waistToSeat: 240, waistToUpperLeg: 290, wrist: 180,
};

const JOBS = {
  hi: { Design: Hi, settings: {} },
  torso: { Design: Brian, settings: { measurements: BODY, only: ['brian.back', 'brian.front', 'brian.sleeve', 'library.sleeve'] } },
  legs: { Design: Titan, settings: { measurements: BODY } },
};

const WORDS = {
  cut: 'Cut', mirrored: 'mirrored', from: 'from', fabric: 'fabric', lining: 'lining', onFold: 'on fold', cutOnFold: 'Cut on fold', grainline: 'Grainline',
  supportFreeSewingBecomeAPatron: 'Support FreeSewing, become a patron', theWhiteInsideOfThisBoxShouldMeasure: 'The white inside of this box should measure',
  theBlackOutsideOfThisBoxShouldMeasure: 'The black outside of this box should measure',
};
const humanize = (w) => w.replace(/([a-z])([A-Z])/g, '$1 $2').toLowerCase();

// The packages print translation keys when no translation plugin is loaded, so this makes the text readable.
// FreeSewing's logo comes off too: it's their mark, and they don't endorse Furge. Credit lives in CREDITS.md.
function clean(svg, prefix) {
  return svg
    .replace(/<\?xml[^>]*\?>/, '')
    .replace(/<use[^>]*href="#logo"[^>]*>(\s*<\/use>)?/g, '')
    .replace(/(id="|href="#)fs-/g, `$1${prefix}-fs-`)
    .replace(/(<tspan[^>]*>)([^<]*)(<\/tspan>)/g, (m, open, body, close) => {
      let t = body
        .replace(/plugin-annotations:(\w+)/g, (_, k) => WORDS[k] || humanize(k))
        .replace(/[A-Z][a-z]+day, [A-Z][a-z]{2} \d+, \d{4}/, '')
        .replace(/\( ephemeral \)/, '');
      if (t.includes(',') && /\bCut\b/.test(t)) t = t.split(',').filter(Boolean).join(' ').replace(/^Cut (\d+)/, 'Cut $1');
      t = t.replace(/\b[a-z]+[A-Z]\w*\b/g, humanize);
      return open + t + close;
    });
}

function partList(raw) {
  const tokens = [...raw.matchAll(/<tspan[^>]*>([^<]*)<\/tspan>/g)].map((m) => m[1].trim());
  const parts = [];
  tokens.forEach((tok, i) => {
    if (!/^\d+$/.test(tok) || !/day, /.test(tokens[i + 1] || '')) return;
    const cutTok = tokens.slice(i, i + 6).find((x) => /plugin-annotations:cut,/.test(x)) || '';
    const qty = (cutTok.match(/plugin-annotations:cut,(\d+)/) || [])[1] || '1';
    parts.push({ nr: +tok, name: humanize(tokens[i + 2]).replace(/^./, (c) => c.toUpperCase()), qty: +qty, mirrored: /mirrored/.test(cutTok), onFold: /[oO]nFold/.test(cutTok) });
  });
  return parts.sort((a, b) => a.nr - b.nr);
}

const [printDir = 'print', dataFile = 'src/generated/fs-data.js'] = process.argv.slice(2).map((p) => resolve(p));
mkdirSync(printDir, { recursive: true });
mkdirSync(dirname(dataFile), { recursive: true });
const data = {};
for (const [name, { Design, settings }] of Object.entries(JOBS)) {
  const pattern = new Design({ sa: 10, complete: true, paperless: false, units: 'metric', ...settings });
  const raw = pattern.use(pluginTheme).draft().render();
  for (const line of pattern.store?.logs?.error || []) console.error(name, 'error:', String(line).slice(0, 200));
  const svg = clean(raw, name);
  const vb = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  writeFileSync(join(printDir, `${name}.svg`), svg);
  data[name] = { svg, w: +vb[1], h: +vb[2], parts: partList(raw) };
  console.log(name, `${(+vb[1] / 10).toFixed(1)} x ${(+vb[2] / 10).toFixed(1)} cm`, data[name].parts.map((p) => `${p.nr}:${p.name}x${p.qty}`).join(' '));
}
writeFileSync(dataFile, `// Generated by freesewing.mjs. Do not edit.\nglobalThis.FurgeFS = ${JSON.stringify(data)};\n`);
